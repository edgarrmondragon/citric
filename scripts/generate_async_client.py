VERSION_DIRECTIVE = re.compile(
    r"^(?P<indent>[ ]*)\.\. version-?(?:added|changed|deprecated)::.*\n"
    r"(?:(?P=indent)[ ]+\S.*\n)*"
    r"(?:[ ]*\n)?",
    re.MULTILINE,
)

MINLIMESURVEY_DIRECTIVE = re.compile(
    r"^[ ]*\.\. minlimesurvey(?:param)?::[ ]+(?P<version>\d+\.\d+\.\d+).*\n(?:[ ]*\n)?",
    re.MULTILINE,
)


class GenerationError(Exception):
    """The sync source can't be transformed mechanically."""


class _Edit:
    def __init__(self, start: int, end: int, text: bytes) -> None:
        self.start = start
        self.end = end
        self.text = text


class _Transformer:
    def __init__(self, source: bytes, method_names: set[str], async_names: set[str]):
        self.source = source
        self.method_names = method_names
        self.async_names = async_names
        self.line_starts = [0]
        for line in source.splitlines(keepends=True):
            self.line_starts.append(self.line_starts[-1] + len(line))
        self.parents: dict[ast.AST, ast.AST] = {}

    def offset(self, lineno: int, col: int) -> int:
        return self.line_starts[lineno - 1] + col

    def start(self, node: ast.expr | ast.stmt) -> int:
        return self.offset(node.lineno, node.col_offset)

    def end(self, node: ast.expr | ast.stmt) -> int:
        assert node.end_lineno is not None
        assert node.end_col_offset is not None
        return self.offset(node.end_lineno, node.end_col_offset)

    def transform(self, node: ast.FunctionDef) -> str:
        """Transform one function definition into its async counterpart."""
        for parent in ast.walk(node):
            for child in ast.iter_child_nodes(parent):
                self.parents[child] = parent

        edits = [_Edit(self.start(node), self.start(node), b"async ")]
        awaited = False

        for sub in ast.walk(node):
            if isinstance(sub, ast.Call) and self._is_awaitable_call(sub):
                awaited = True
                edits += self._await(sub)
            elif isinstance(sub, ast.Attribute) and self._is_self(sub.value):
                edits += self._check_self_attribute(sub, node.name)

        if awaited:
            self._check_await_context(node)

        # Start at the beginning of the line of the first decorator, or of the `def`
        first = node.decorator_list[0] if node.decorator_list else node
        begin = self.line_starts[first.lineno - 1]
        end = self.end(node)

        text = bytearray(self.source)
        for edit in sorted(edits, key=lambda e: (e.start, e.end), reverse=True):
            text[edit.start : edit.end] = edit.text
        shift = sum(len(e.text) - (e.end - e.start) for e in edits)
        return text[begin : end + shift].decode()

    @staticmethod
    def _is_self(node: ast.expr) -> bool:
        return isinstance(node, ast.Name) and node.id == "self"

    def _is_awaitable_call(self, call: ast.Call) -> bool:
        func = call.func
        if not isinstance(func, ast.Attribute):
            return False

        # self.session.<rpc>(...)
        if (
            isinstance(func.value, ast.Attribute)
            and self._is_self(func.value.value)
            and func.value.attr == "session"
        ):
            return True

        # self.<generated or handwritten method>(...)
        return self._is_self(func.value) and func.attr in self.async_names

    def _await(self, call: ast.Call) -> list[_Edit]:
        parent = self.parents.get(call)
        postfix = (
            isinstance(parent, ast.Attribute)
            or (isinstance(parent, ast.Subscript) and parent.value is call)
            or (isinstance(parent, ast.Call) and parent.func is call)
        )
        start, end = self.start(call), self.end(call)
        if postfix:
            return [_Edit(start, start, b"(await "), _Edit(end, end, b")")]
        return [_Edit(start, start, b"await ")]

    def _check_self_attribute(self, attr: ast.Attribute, method: str) -> list[_Edit]:
        parent = self.parents.get(attr)
        is_call_func = isinstance(parent, ast.Call) and parent.func is attr

        if attr.attr in FORBIDDEN_ATTRIBUTES:
            msg = f"{method}: `self.{attr.attr}` isn't supported by the async client"
            raise GenerationError(msg)

        if attr.attr in self.method_names and not is_call_func:
            msg = f"{method}: `self.{attr.attr}` is used without being called"
            raise GenerationError(msg)

        if is_call_func and attr.attr in self.method_names - self.async_names:
            msg = (
                f"{method}: calls `self.{attr.attr}`, which is neither generated nor "
                "hand-written. Add it to HANDWRITTEN"
            )
            raise GenerationError(msg)

        return []

    def _check_await_context(self, func: ast.FunctionDef) -> None:
        """Reject constructs where ``await`` would silently change semantics."""
        for sub in ast.walk(func):
            if sub is func:
                continue
            if isinstance(sub, (ast.Lambda, ast.FunctionDef, ast.AsyncFunctionDef)):
                msg = f"{func.name}: nested function or lambda in an awaiting method"
                raise GenerationError(msg)
            if isinstance(sub, ast.GeneratorExp):
                msg = f"{func.name}: generator expression in an awaiting method"
                raise GenerationError(msg)


def _drop_old_minlimesurvey(match: re.Match[str]) -> str:
    version = tuple(int(part) for part in match["version"].split("."))
    return "" if version < MIN_LIMESURVEY else match[0]


def _strip_version_notes(source: str) -> str:
    source = VERSION_DIRECTIVE.sub("", source)
    source = MINLIMESURVEY_DIRECTIVE.sub(_drop_old_minlimesurvey, source)
    # A docstring that now ends with blank lines before the closing quotes
    return re.sub(r"\n(?:[ ]*\n)+([ ]*\"\"\")", r"\n\1", source)


def generate() -> str:
    """Generate the source of the async methods module.

    Returns:
        The module source, before formatting.
    """
    source = SOURCE.read_bytes()
    tree = ast.parse(source)
    client = next(
        n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == "Client"
    )
    functions = [n for n in client.body if isinstance(n, ast.FunctionDef)]
    method_names = {
        f.name
        for f in functions
        if not any(
            isinstance(d, ast.Name) and d.id == "property" for d in f.decorator_list
        )
    }

    unknown = HANDWRITTEN - method_names
    if unknown:
        msg = f"Not methods of Client: {sorted(unknown)}"
        raise GenerationError(msg)

    generated = {
        f.name
        for f in functions
        if f.name in method_names
        and f.name not in HANDWRITTEN
        and not f.name.startswith("__")
    }
    transformer = _Transformer(source, method_names, generated | HANDWRITTEN)
    chunks = [
        _strip_version_notes(transformer.transform(f))
        for f in functions
        if f.name in generated
    ]

    body = "\n\n".join(chunks)
    return f"{HEADER}\n{body}\n"


def _ruff(*args: str) -> list[str]:
    exe = shutil.which("ruff")
    return [exe, *args] if exe else ["uv", "run", "ruff", *args]


def format_source(source: str) -> str:
    """Prune unused imports and format with the project's ruff configuration.

    Args:
        source: The generated source.

    Returns:
        The formatted source.
    """
    # Use a temporary file inside the repo, so that the project's config applies
    with tempfile.NamedTemporaryFile(
        "w",
        suffix=".py",
        dir=TARGET.parent,
        delete=False,
        encoding="utf-8",
    ) as tmp:
        tmp.write(source)
        path = Path(tmp.name)

    try:
        for args in (
            ("check", "--fix", "--select", "F401,I001", "--quiet"),
            ("format", "--quiet"),
        ):
            subprocess.run(_ruff(*args, str(path)), check=True, cwd=ROOT)  # ruff: ignore[subprocess-without-shell-equals-true]
        return path.read_text(encoding="utf-8")
    finally:
        path.unlink(missing_ok=True)


def main() -> int:
    """Run the generator."""
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument(
        "--write",
        action="store_true",
        help="Write the generated module. This is the default, unless --check is used.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Don't write; exit with 1 if the generated module is out of date.",
    )
    args = parser.parse_args()

    try:
        output = format_source(generate())
    except GenerationError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2

    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != output:
            print(
                f"{TARGET.relative_to(ROOT)} is out of date. "
                "Run scripts/generate_async_client.py",
                file=sys.stderr,
            )
            return 1
        return 0

    TARGET.write_text(output, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
